export type Language = 'en' | 'it'
export type Message = keyof typeof messages
export type Translate = (message: Message) => string

export function translator(language: Language): Translate {
  return message => messages[message][language === 'it' ? 1 : 0]
}

export function errorText(t: Translate, code: string): string {
  return t(Object.hasOwn(messages, code) ? code as Message : 'operation-failed')
}
